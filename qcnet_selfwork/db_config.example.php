<?php
// =============================================================================
// db_config.example.php — Database connection template
// =============================================================================
// Copy this file to db_config.php and fill in your real credentials.
// db_config.php itself should NEVER be committed to version control or
// shared publicly — it's the shared secret every domain deployment uses
// to reach the same central database.
//
// IMPORTANT — the "sync across domains" part of this setup is entirely
// this file: every domain (siteA.com, siteB.com, ...) gets its own copy
// of db_config.php, but all of them point at the SAME DB_HOST/DB_NAME.
// There is no other synchronization mechanism — MySQL itself handles
// concurrent reads/writes from multiple app servers correctly as long as
// they're all talking to the same instance.
// =============================================================================

define('DB_HOST', 'localhost');        // your database host — ask your hosting provider if unsure; for a shared multi-domain setup this usually needs to be a hostname reachable from all your domains, not "localhost" unless they're all on the same physical server
define('DB_PORT', 3306);               // default MySQL/MariaDB port — change only if your host uses a non-standard one
define('DB_NAME', 'your_database_name');
define('DB_USER', 'your_database_user');
define('DB_PASS', 'your_database_password');

// ---------------------------------------------------------------------------
// FILE_LINK_SECRET — used by file_links.php to sign + encrypt the tokens
// for large-file (>1MB) cross-domain links (see sql/schema.sql's
// file_links table). This MUST be the exact same value on every domain
// deployment, or a link generated by one domain won't verify on another.
// Generate a strong random value once and copy it to every domain's
// db_config.php — do not use the placeholder below in production.
//
// Generate one with: php -r "echo bin2hex(random_bytes(32));"
// ---------------------------------------------------------------------------
define('FILE_LINK_SECRET', 'CHANGE_ME_TO_A_RANDOM_64_CHAR_HEX_STRING_SHARED_ACROSS_ALL_DOMAINS');

// ---------------------------------------------------------------------------
// DASH_ENC_KEY_SHARED — encryption key for the dashboard's secure_tables
// data (users, payments, products, tenants, etc. — see db_dash_common.php).
// The original per-domain auto-generated key (data_dash/sys_key.php)
// doesn't work once this data is shared across domains: each domain
// would have a different key and couldn't decrypt data another domain
// wrote. This MUST be the exact same value on every domain, exactly
// like FILE_LINK_SECRET above — generate once, copy everywhere.
//
// Generate one with: php -r "echo bin2hex(random_bytes(32));"
// ---------------------------------------------------------------------------
define('DASH_ENC_KEY_SHARED', 'CHANGE_ME_TO_A_RANDOM_64_CHAR_HEX_STRING_SHARED_ACROSS_ALL_DOMAINS');

// ---------------------------------------------------------------------------
// THIS_DOMAIN — this deployment's own public URL, used when generating
// file links so other domains know where to fetch a large file from.
// Set this to whichever domain THIS copy of the app is actually running
// on — it will be different on every deployment, unlike everything else
// in this file.
// ---------------------------------------------------------------------------
define('THIS_DOMAIN', 'https://example.com');

// =============================================================================
// OPTIONAL: multiple joined databases (not active by default)
// =============================================================================
// Everything above this line is the CURRENT, ACTIVE setup: one shared
// database, all domains connect to it directly via DB_HOST/DB_NAME/etc.
// That is what's running right now and confirmed working — nothing
// below this line changes that unless you deliberately fill it in.
//
// This section exists so that, WHEN you actually need per-domain
// databases (e.g. one domain's traffic outgrows a single shared
// instance, or you want physical data separation for a specific
// tenant), the config slot is already here — you won't need to touch
// db.php's connection logic itself, just fill in real values below and
// write the actual sync/replication SQL for your specific situation at
// that time. Building real multi-database replication now, before it's
// needed, would mean guessing at conflict-resolution rules (what
// happens when the same room is edited from two different databases
// within the same second?) without a real scenario to design against —
// better to design that when there's an actual second database and a
// real access pattern to build around.
//
// DB_CONNECTIONS is an array of additional named connections. Each
// domain's own db_config.php can define as many of these as it needs.
// Leave this as an empty array (the default) to keep the current
// single-shared-database behavior exactly as-is — db() (in db.php)
// only ever uses DB_HOST/DB_NAME/etc. above, never this array, unless
// you explicitly call db_named($connectionName) instead of db().
//
// Example of what filling this in would look like, once needed:
//   define('DB_CONNECTIONS', [
//       'domainB' => [
//           'host' => 'sql123.infinityfree.com',
//           'port' => 3306,
//           'name' => 'if0_XXXXXXX_domainb',
//           'user' => 'if0_XXXXXXX',
//           'pass' => 'the_real_password',
//       ],
//   ]);
// Then, in code, db_named('domainB') returns a separate PDO connection
// to that database, alongside db() which still returns the main shared
// connection — the two are never mixed automatically.
define('DB_CONNECTIONS', []);

